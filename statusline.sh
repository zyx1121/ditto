  [(.model.display_name // ""),
   (.context_window.used_percentage // ""),
   (.rate_limits.five_hour.used_percentage // ""),
   (.rate_limits.seven_day.used_percentage // "")] | @tsv' <<<"$input" 2>/dev/null)"

COLS=${COLUMNS:-80}
