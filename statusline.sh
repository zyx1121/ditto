)
B=(
'\033[49m \033[49m \033[49m \033[49m \033[49;38;5;16m▄\033[49;38;5;16m▄\033[49m \033[49m \033[49;38;5;16m▄\033[38;5;16;48;2;236;224;250m▀\033[38;5;16;48;2;236;224;250m▀\033[49;38;5;16m▄\033[49m \033[49m \033[49m \033[49m \033[0m'
'\033[49m \033[49m \033[49;38;5;16m▄\033[38;5;16;48;2;195;161;230m▀\033[38;2;236;224;250;48;2;195;161;230m▀\033[49;38;2;236;224;250m█\033[38;5;16;48;2;195;161;230m▀\033[38;5;16;48;2;195;161;230m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;2;236;224;250;48;5;16m▀\033[38;5;16;48;2;195;161;230m▀\033[49;38;5;16m█\033[38;5;16;48;2;236;224;250m▀\033[38;5;16;48;2;236;224;250m▀\033[49;38;5;16m▄\033[0m'
'\033[49m \033[49;38;5;16m▄\033[38;5;16;48;2;195;161;230m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;5;16;48;2;195;161;230m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;2;195;161;230;48;5;16m▀\033[38;2;195;161;230;48;5;16m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;5;16m█\033[0m'
'\033[49m \033[49;38;5;16m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;5;16;48;2;195;161;230m▀\033[38;5;16;48;2;195;161;230m▀\033[38;5;16;48;2;195;161;230m▀\033[38;5;16;48;2;195;161;230m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;2;195;161;230;48;2;236;224;250m▀\033[49;38;5;16m█\033[49m \033[0m'
'\033[49;38;5;16m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[38;2;195;161;230;48;5;16m▀\033[38;2;236;224;250;48;5;16m▀\033[38;5;16;48;2;195;161;230m▀\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;195;161;230m█\033[49;38;2;236;224;250m█\033[49;38;2;236;224;250m█\033[49;38;2;236;224;250m█\033[49;38;2;195;161;230m█\033[49;38;5;16m█\033[0m'
